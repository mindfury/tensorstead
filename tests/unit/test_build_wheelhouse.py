"""The appliance dependency set is exactly the lock, for the target, hash-verified.

CodeGuard CG-14: appliances let pip resolve the wheel's lower-bounded
dependencies fresh on every deploy. ``scripts/build_wheelhouse.py`` builds the
locked set instead; these pin its refusals.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import subprocess
from pathlib import Path
from typing import Any

import pytest

pytestmark = pytest.mark.unit

_SPEC = importlib.util.spec_from_file_location(
    "build_wheelhouse", Path(__file__).resolve().parents[2] / "scripts" / "build_wheelhouse.py"
)
assert _SPEC and _SPEC.loader
wh: Any = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(wh)

_GOOD = b"a wheel's bytes"
_GOOD_HASH = "sha256:" + hashlib.sha256(_GOOD).hexdigest()
_OTHER = "sha256:" + "0" * 64


def _export(*entries: str) -> str:
    return "\x1b[32m# autogenerated\x1b[39m\n" + "\n".join(entries) + "\n"


def _fake_download(files: dict[str, bytes]) -> Any:
    def run(args: list[str], **_kw: Any) -> Any:
        if "download" in args:
            out = Path(args[args.index("-d") + 1])
            for name, data in files.items():
                (out / name).write_bytes(data)
        return subprocess.CompletedProcess(args, 0, "", "")

    return run


def test_markers_are_evaluated_for_the_target_not_this_machine(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    exported = _export(
        f"linuxonly==1.0 ; sys_platform == 'linux' \\\n    --hash={_GOOD_HASH}",
        f"winonly==1.0 ; sys_platform == 'win32' \\\n    --hash={_OTHER}",
        "    \x1b[32m# via something\x1b[39m",
    )
    monkeypatch.setattr(wh, "_exported", lambda: wh.re.sub(r"\x1b\[[0-9;]*m", "", exported))
    monkeypatch.setattr(
        wh.subprocess, "run", _fake_download({"linuxonly-1.0-py3-none-any.whl": _GOOD})
    )

    manifest = wh.build("linux-aarch64-cp312", tmp_path / "wh")

    requirements = (tmp_path / "wh" / "requirements.txt").read_text()
    assert "linuxonly==1.0" in requirements, "a Linux dependency was dropped on a non-Linux build"
    assert "winonly" not in requirements
    assert manifest["files"] == {"linuxonly-1.0-py3-none-any.whl": _GOOD_HASH}
    assert json.loads((tmp_path / "wh" / "wheelhouse.json").read_text())["target"] == (
        "linux-aarch64-cp312"
    )


def test_a_pin_without_a_hash_is_refused(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(wh, "_exported", lambda: _export("unhashed==1.0"))
    with pytest.raises(SystemExit, match="no hash"):
        wh.build("linux-aarch64-cp312", tmp_path / "wh")


def test_a_downloaded_file_not_in_the_lock_is_refused(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setattr(wh, "_exported", lambda: _export(f"pkg==1.0 --hash={_OTHER}"))
    monkeypatch.setattr(wh.subprocess, "run", _fake_download({"pkg-1.0-py3-none-any.whl": _GOOD}))
    with pytest.raises(SystemExit, match="not in the lock"):
        wh.build("linux-aarch64-cp312", tmp_path / "wh")


def test_a_missing_wheel_is_refused(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(
        wh, "_exported", lambda: _export(f"a==1 --hash={_GOOD_HASH}", f"b==1 --hash={_OTHER}")
    )
    monkeypatch.setattr(wh.subprocess, "run", _fake_download({"a-1-py3-none-any.whl": _GOOD}))
    with pytest.raises(SystemExit, match="downloaded 1 wheels for 2 pins"):
        wh.build("linux-aarch64-cp312", tmp_path / "wh")


def test_the_download_resolves_nothing_and_takes_only_binaries(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    seen: dict[str, list[str]] = {}

    def run(args: list[str], **_kw: Any) -> Any:
        seen["args"] = args
        (Path(args[args.index("-d") + 1]) / "a-1-py3-none-any.whl").write_bytes(_GOOD)
        return subprocess.CompletedProcess(args, 0, "", "")

    monkeypatch.setattr(wh, "_exported", lambda: _export(f"a==1 --hash={_GOOD_HASH}"))
    monkeypatch.setattr(wh.subprocess, "run", run)
    wh.build("linux-aarch64-cp312", tmp_path / "wh")
    for flag in ("--no-deps", "--only-binary=:all:", "--require-hashes"):
        assert flag in seen["args"], flag
